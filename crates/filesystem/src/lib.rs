//! `filesystem` —— 外部 QSPI NOR Flash 上的**日志结构文件系统**
//! （**平台需求 EV-2 / TS-2**）。
//!
//! 纯逻辑、`no_std`、**零分配**、无外部依赖。掉电安全靠"分块齐 + 记录级 CRC"
//! 的**策略**保证，而策略可以在主机上用任意时刻的掉电注入穷举验证 ——
//! 与 `ports::double_bank` 同一条纪律：把不可测的部分（真实擦写时序）
//! 压缩到只剩 [`BlockDevice`] 四个方法，其余全部可测。
//!
//! # 为什么要有它
//!
//! `flash-layout` 把外部 Flash 收敛成"启动/升级必需的 6 个分区 + 一整块文件系统"，
//! 全部应用数据（应用参数、现场标定、复位台账、黑匣子、离线缓冲）都以**文件**
//! 形式住在这里。它们的差异是文件语义：
//!
//! | 语义 | 接口 | 掉电后读到 |
//! |------|------|------------|
//! | 整体覆盖的文件 | [`FileSystem::write_file`] | 上一个完整版本，或新的完整版本 |
//! | 只追加的日志 | [`FileSystem::append`] / [`FileSystem::read_log`] | 到最后一个完整分块为止 |
//! | 删除 | [`FileSystem::remove`] | 不存在（墓碑已落盘） |
//!
//! # 介质布局
//!
//! 整个分区按**块**（真实器件 64 KiB）分配。块头 16 字节，记录头 16 字节，
//!
//! ```text
//! 块 0                        块 1                       块 2
//! ┌──────────┬───────────┐   ┌──────────┬───────────┐   ┌──────────┐
//! │ 块头 16B │ 记录 记录…│   │ 块头 16B │ 记录 记录…│   │ 块头 16B │
//! └──────────┴───────────┘   └──────────┴───────────┘   └──────────┘
//! ```
//!
//! # 版本与"提交"
//!
//! 一个文件的一次写入 = **一组带同一版本号的分块记录**，写到别处（旧版本原地不动）。
//! 没有单独的提交记录：只有当一个版本的**全部分块都齐、且每条记录的 CRC-32 都对**时，
//! 这个版本才算提交。于是掉电只可能留下"上一个完整版本"或"新的完整版本"：
//!
//! ```text
//! 旧版本(完整) ──覆盖写──▶ 新版本分块 0 ✓ 分块 1 ✓ 分块 2 ✗(掉电)
//!                            ↑ 不完整 ⇒ 读路径忽略它，读回旧版本
//! ```
//!
//! 完整性判定需要"这个版本已经见过哪些分块"，因此每个名字在内存里带一张 256 位的
//! 位图（`index` 模块的文档解释了为什么是位图而不是计数器、为什么每个名字要留
//! 两个候选版本）。**版本号是全局单调计数器**，不复用 —— 这条设计约束来自一个真实
//! 缺陷：文件名索引只有 64 个槽位，删除过的名字会腾出槽位，于是"按名字记版本号"
//! 会让同名重建的记录与介质上的残留记录撞号，而撞号意味着两条不同内容的记录被当成
//! 同一个版本的分块，读出"半新半旧"。
//!
//! # 掉电安全的三条依据
//!
//! 1. **NOR 只能把 1 写成 0**。一条记录分几次 `program` 落下
//!    （记录头（含 CRC）→ 名字 → 日志偏移前缀 → 数据），撕裂时留在介质上的
//!    一定是完整记录的**前缀**，CRC 必然对不上（除非整条落盘）。
//! 2. **扫描按声明长度跳过坏记录**。撕裂记录声明长度 ≥ 实际写入长度（缺失字节读回
//!    `0xFF`，而 `0xFF` 是各字节位置上的最大值），因此跳过永远不会踩进后面被写过的字节。
//! 3. **垃圾回收先复制、后擦除**，且只在活记录全部复制成功之后才擦源块。
//!    掉电只会留下"源块完好"或"源块与副本并存（内容相同、CRC 相同）"。
//!
//! # 内存用量是静态可知的
//!
//! 不分配堆内存。内存索引的两个维度是编译期常量：`MAX_BLOCKS`（块视图，
//! 每块约 40 字节）与 `MAX_FILES`（名字索引，每个文件约 152 字节 —— 大部分是
//! 两个版本候选各自的 256 位分块位图）。实测（x86_64 主机）：
//!
//! ```text
//! FileSystem<Flash, 256, 64>   20056 字节   ← 默认值
//! FileSystem<Flash, 190, 64>   18472 字节   ← 11.88 MiB / 64 KiB = 190 块
//! FileSystem<Flash,  32, 16>    4648 字节   ← 只放几个小文件的场合
//! ```
//!
//! 也就是说，把 `MAX_FILES` 从 64 收到 16 能省下 7 KiB 量级的 OCRAM，
//! 代价只是"最多同时存在 16 个文件"。
//!
//! # 限制（都有测试钉住）
//!
//! - 文件名 ≤ 31 字节，ASCII 可打印、不含 `/`（[`MAX_NAME_LEN`]）；
//! - 目录最多 64 个文件（[`MAX_FILES`]）；墓碑条目会被回收，删除后再建不算泄漏；
//! - 文件大小不限（跨块），但单个文件最多 256 个分块 —— 分块取"一块装得下的
//!   最大数据"，因此在 64 KiB 块的器件上这是约 16 MiB，超过整个分区；
//! - 日志分块序号是 `u16`：单个版本最多 65535 次追加，超出返回 [`FsError::LogFull`]。
//!
//! # 已知取舍（详见交付说明）
//!
//! - 读路径是**扫描式**的：不做堆分配，也就不保留"每条记录在哪个块"的常驻目录。
//!   一次读取的代价与分区大小同阶（主机上是微秒级，真机 QSPI 上是毫秒级）。
//!   要把它降下来，正路是给每个文件加"块指针链"（littlefs 的 CTZ skip-list）。
//! - 记录头被破坏时，扫描器会逐字节**重同步**找回后面的记录；代价是该块一次全扫描。

