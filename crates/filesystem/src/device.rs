//! 块设备抽象：**唯一**不能在主机上测试的那一层。
//!
//! # 为什么接口只有四个动作
//!
//! 与 `ports::raw::RawMedium` 同一个思路：把"不可测的部分"压到最小。
//! 掉电原子性的**策略**（版本完整性 + 记录级 CRC + 日志结构 + 垃圾回收）全部
//! 在本 crate 的上层，可以在主机上用任意时刻的掉电注入穷举验证；本 trait 只描述
//! "读一段、擦一块、写一段"。
//!
//! 于是"文件系统会不会读出垃圾"被拆成两半：
//!
//! | 问题 | 验证手段 |
//! |------|----------|
//! | 策略对不对（版本、CRC、GC、磨损） | 主机穷举掉电点（快、可复现） |
//! | 介质行为对不对（时序、掉电时的字节状态） | HIL 真机断电（慢、不可替代） |
//!
//! # 实现方的三条义务
//!
//! 1. **`read` 要么填满整个缓冲区，要么返回错误**。不允许"部分读成功"：
//!    文件系统会把"少读了几个字节"当成介质损坏，而真正的原因可能是驱动 bug ——
//!    让它尽早以错误形式暴露，比悄悄按 0xFF 处理要好。
//! 2. **`program` 只允许写"从未写过的 0xFF 区域"**（NOR 语义）。文件系统保证
//!    自己永不覆盖已写字节（见 crate 文档的写入顺序论证），实现方负责断言这一点：
//!    真实的 W25Q256 在没有擦除的情况下重复编程会得到按位与的结果，
//!    静默产生"半对半错"的数据，这是最难查的一类缺陷。
//! 3. **`erase_block` 擦除整块**，且块大小必须等于 [`BlockDevice::block_size`]。
//!    擦除是唯一能把位从 0 变回 1 的手段，也是块级磨损的来源。
//!
//! # 分区偏移
//!
//! 本 crate 的偏移一律是**相对文件系统分区起点**的（0 起）。真实器件上文件系统
//! 位于 `flash_layout::FILESYSTEM_OFFSET`，由 BSP 的适配器加上基址 ——
//! 把基址留在 BSP 是刻意的：文件系统不该知道别的分区在哪，否则"写错分区"
//! 这类会擦掉启动映像的缺陷就只隔着一次加法。

use crate::error::FsError;

/// 可擦除块设备。
pub trait BlockDevice {
    /// 块大小（字节）。QSPI NOR 上是 65536（64 KiB 块擦除）。
    fn block_size(&self) -> u32;

    /// 块数量。
    fn block_count(&self) -> u32;

    /// 从 `offset` 起**读满** `out`。
    ///
    /// # Errors
    ///
    /// 越界、驱动故障，或无法读满整个缓冲区。
    fn read(&mut self, offset: u32, out: &mut [u8]) -> Result<(), FsError>;

    /// 擦除第 `index` 块（整块）。
    ///
    /// # Errors
    ///
    /// 越界或驱动故障。
    fn erase_block(&mut self, index: u32) -> Result<(), FsError>;

    /// 把 `data` 写到 `offset`（该区域必须处于擦除态）。
    ///
    /// # Errors
    ///
    /// 越界、对非擦除区域编程，或驱动故障。
    fn program(&mut self, offset: u32, data: &[u8]) -> Result<(), FsError>;
}
