// 2026-10-13：这个开关**同时**是 `check-code-placement` 门禁盲区的充分判据
// ---------------------------------------------------------------------------
//
// 两件事在这次实测中被澄清（都会影响以后怎么读它的结果）：
//
// ## ① 它跑在 **`idle_body`** 里，不是 `#[init]` 里（名字有误导性，但保留）
//
// `report_flash_selftest` 的调用点在空闲循环**之前**、`idle_body` 之内
// （`firmware/src/main.rs` 的 `idle_body`，紧接 `run_boot_post` 之后）。
// 它属于"启动序列"，但不属于 `#[init]` —— 因此**中断是使能的**，
// 那次擦除是可被打断的，而不是一段关中断窗口。
// 日志顺序能自证这一点：`flash : 自证` 出现在 `ram dma`（由 `report_flexspi_regs`
// 打印）**之前**，而两者都在 `idle_body` 里。
//
// ## ② 自从 v0.10（`idle` 搬进 `.xip`）之后，这条自证**就是在 XIP 代码里跑的**
//
// 而 `check-code-placement` 门禁有一条**看不见内联**的盲区：如果 Flash 驱动被
// `lto = "fat"` 内联进了 `idle_body`（也就是进了 `.xip`），符号表不会有任何变化。
// 那件事的后果是自锁 —— 擦除期间 XIP 取指要经同一个控制器，而它正忙。
//
// ⇒ **唯一充分的判据就是这个开关**：
//
// - 打开它，若**能打印出自证结果**（PASS 或 FAIL），说明擦写在 XIP 代码路径里
//   能完成（最坏是被停等，而不是死锁）；
// - 若设备**停在这里不再输出心跳**，则证实驱动确实被内联进了 `.xip`。
//
// **真机实测（2026-10-13，PASS）**：
//
// ```text
// flash : 自证(跨页+非对齐) PASS 擦写三例=ok bad=0 擦回=ok sector=0x1fff000
// beat=1 uptime=183.401s tick=8541 ... rt=ok txdrop=0
// beat=2 uptime=184.401s tick=9541 ...   ← 心跳继续，无死锁
// ```
//
// 与静态证据一致：`.xip` 的反汇编 4,453 行里**零个外设地址引用**
//（`arm-none-eabi-objdump -d --section=.xip | grep -ciE 402a8` = 0），
// 即驱动确实没有被内联进来。**两条独立证据指向同一结论。**

