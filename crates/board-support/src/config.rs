// ## 结论二：真机逼出来的三条硬事实（都已写进代码注释）
//
// 1. **`IPCR1.IDATSZ` 必须等于"这一个 IP 命令真正送进 FIFO 的字节数"**。
//    我一度把 256 B 整页声明给控制器、却只灌进 32 B ⇒ 控制器要 256、FIFO 只有 32
//    ⇒ 写相位停摆。判据：`失配 @32 ... got=...ffffffff`（**前 32 字节完全正确**）。
//    ⇒ 分块单位 = [`crate::flexspi_ip::ip_burst_bytes`]；
