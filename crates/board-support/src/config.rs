// ## 结论一：**写路径必须走寄存器级，ROM 的 `program` 在本板报成功但不写**
//
// 两条路径在同一时刻对照：寄存器路径 `PASS`（写后 XIP 读回逐字节一致），
// ROM 路径返回成功、器件读回全 `0xFF`。⇒ `rom_flash::program_page` 已改为转调
