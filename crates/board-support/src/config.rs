// 修之前：写使能探针 wren_ok=true status_after_wren=0x00 (WIP=0 WEL=0)  ← 与"擦除能成"矛盾
// 修之后：写使能探针 wren1_ok=true sr1a=0x02 wren2_ok=true sr1b=0x02 (WIP=0 WEL=1)  ← 自洽
// ```
