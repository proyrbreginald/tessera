/// 外部 QSPI NOR 容量：Winbond `W25Q256JVEQ` = 32 MiB。✅
///
/// 与 [`FLASH_SIZE`] 是同一个值；两者由 `firmware/build.rs` 生成的
/// `const` 断言绑死，不一致就是**编译失败**（而不是"能烧录但起不来"）。
pub const FLASH_SIZE_BYTES: u32 = 32 * 1024 * 1024;

// 编译期把两条界限的关系钉住：可寻址窗口必须落在器件容量之内，
// 且必须与分区表里的 XIP 窗口一致（分区表是它的唯一来源）。
const _: () = {
    assert!(ADDRESSABLE_BYTES <= FLASH_SIZE);
    // 分区表的可寻址窗口是本模块的上界来源：它若缩回 16 MiB，这里会**编译失败**，
    // 从而强迫"改 LUT"与"改窗口"两件事一起发生。
    assert!(ADDRESSABLE_BYTES == flash_offset(flash_layout::XIP_WINDOW));
};

/// 把分区表里的 `u32` Flash 偏移转成本模块接口用的 `usize`。
///
/// 为什么这里允许 `as`：`usize` 在目标平台（thumbv7em）就是 32 位，而分区表的
/// 值域由 `xtask check-flash-map` 保证 < 32 MiB，转换不可能丢信息。
/// `usize::try_from` 在 const 上下文里不可用，`as` 是唯一可行的写法，
/// 因此就地允许该 lint，而不是在整个文件上放宽。
pub(crate) const fn flash_offset(value: u32) -> usize {
    #[allow(clippy::as_conversions)]
    let converted = value as usize;
    converted
}

/// 文件系统分区起点：**全部应用数据都在这里**。
///
/// 分区本身不在这里定义 —— 唯一事实来源是 `flash_layout`，
/// 它同时被 `xtask check-flash-map` 与文档使用，改一处即三处一致。
pub const FILESYSTEM_BASE: usize = flash_offset(flash_layout::FILESYSTEM_OFFSET);

/// 应用数据在文件系统里的名字（**平台约定的词汇表**，应用可在此基础上扩展）。
///
/// **为什么数据用文件而不是各自的分区**：应用参数（整体覆盖）、标定（长期有效）、
/// 台账/黑匣子/离线缓冲（只追加）、出厂信息（写一次）之间的差异是**文件语义**，
/// 不是物理布局。用文件表达就不必为每一类数据维护一套偏移、对齐与擦除策略。
/// 文件名使用 **Linux 风格绝对路径**（`filesystem::path`）：目录由路径前缀隐含，
/// 没有独立目录 inode；路径总长 ≤31 字节、可打印 ASCII、不允许 `//`/`.`/`..`。
/// 旧式无 `/` 名字仍可读（兼容迁移），但新代码一律用绝对路径。
pub mod files {
    /// 应用参数。
    pub const CONFIG: &str = "/config/config.bin";
    /// 现场标定。
    pub const CALIBRATION: &str = "/config/calib.bin";
    /// 复位台账（只追加）。
    pub const RESET_LOG: &str = "/log/reset.log";
    /// 事件黑匣子（只追加）。
    pub const BLACKBOX: &str = "/log/blackbox.log";
    /// 遥测/事件缓冲（只追加）。
    pub const SPOOL: &str = "/log/spool.log";
    /// 出厂信息（写入一次）。
    pub const FACTORY: &str = "/factory/factory.bin";
}

// 历史上出现过一次"双属主"事故：过渡期的三张原始偏移表与文件系统**块 0 物理重叠**，
// 其中一方不知道自己会被另一方擦掉。现在持久化只有一个属主：文件系统；
// 还没接线的持久化端口用 `ports::store::NullStore` 明确说"不可用"，
// 绝不假装成功（见 `ports::store` 的文档）。

/// 外部 QSPI NOR 的**器件**容量（`usize` 版本）：32 MiB。
///
/// ⚠️ 这不是可寻址窗口！见 [`ADDRESSABLE_BYTES`] —— 器件上电处于 3 字节地址模式，
/// 只有前 16 MiB 能通过 XIP 访问。把器件容量当成访问上界是一个**会静默损坏数据**的
/// 缺陷：越过 16 MiB 的访问不会报错，而是把高位地址丢掉、**别名到低 16 MiB**，
/// 于是"擦除日志区"可能实际擦掉启动头。
pub const FLASH_SIZE: usize = 32 * 1024 * 1024;

/// 是否启用 MPU 区域 + I/D cache。
///
/// 保留成开关是为了**可对照测量**：同一份代码分别以 `true` / `false` 构建，
/// 就能拿到"开缓存前 / 后"的真实数字，而不是凭感觉说"应该会快"。
/// 生产构建应为 `true`。
pub const MPU_AND_CACHE_ENABLED: bool = true;

/// 通过 XIP 映射**真正可寻址**的字节数：整片 32 MiB。
///
/// 依据：FCB 的 LUT 用**专用 4 字节地址操作码**（读 `0xEC`、页编程 `0x34`、
/// 扇区擦除 `0x21`，地址相位 `0x20` —— 见 `flash` 模块），因此整片器件都在窗口内。
///
/// ⚠️ 这个值的前提是"LUT 保持 4 字节地址相位"。若有人把它换回 3 字节（`0xEB`/`0x18`），
/// 窗口就会缩回 16 MiB，而越界访问**不报错**、会别名到低 16 MiB。
/// 因此这里不是照抄器件容量：它与分区表的 `XIP_WINDOW` 由编译期断言绑死，
/// 而 `flash` 模块另有一条**运行期自检**（见 `four_byte_addressing_ok`）。
pub const ADDRESSABLE_BYTES: usize = FLASH_SIZE;
