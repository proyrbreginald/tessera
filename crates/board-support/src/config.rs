// ⚠️ 途中我自己写错过一次 `IPRXFSTS` 的偏移（写成 `0xF8`，**那是保留区**；官方是
// `0xF0`，`PERI_FLEXSPI.h:149`）。症状是"所有状态读超时、连擦除也失败"——
// **偏移必须逐条从 SDK 结构体注释抄，不能按邻近推**。
//
// ## 2. 编程失败的**新判据**：写相位 SCLK 停摆（官方出口，此前从未被解码）
//
// 把 `INTR` **原始字**打出来之后（以前只解码 bit0/1/3）：
//
// ```text
// 编程失败 stage=12 intr=0x00000260（原始）fill_before=0 fill_after=0 rounds=0
// ```
//
// `0x260` = `IPCMDERR(0x8) | IPTXWE(0x40) | SCKSTOPBYWR(0x200)`；
// `SCKSTOPBYWR` 的官方定义是 **"SCLK is stopped during command sequence because
// Async TX FIFO empty"**（`PERI_FLEXSPI.h:489`）⇒ **数据相位因为 TX FIFO 空了而停摆**。
// 而 `fill_before=0` 说明**预灌阶段一个字节都没进 FIFO**（`IPTXFSTS.FILL` 读回 0）。
//
// ## 3. 下一步：先用零风险探针把"TFDR 写没进 FIFO"切开
//
// `flexspi_ip::fill_probe()` 已经接进 `report_flexspi_regs`，并且这一版把它做成
// **四个互斥读数**（不是一次成败）——**不发任何命令、不碰器件、零风险**：
//
// ```text
// flexspi  : FIFO 探针 clear=? after1=? after4=? reclear=? | MCR0 ATDFEN=? ARDFEN=?
// ```
//
// | 读数 | 结论 |
// |---|---|
// | `after1 = 0` | **`TFDR` 的第一次写就没进队列** ⇒ 与命令/LUT/器件全无关；查 `IPTXFCR` / `IPTXSTS` 读写语义 |
// | `after1 = 1`、`after4 ≠ 4` | 只有首字进入 ⇒ 突发写形状问题（`TFDR` 递增地址的写法） |
// | `after1 = 1`、`after4 = 4` | 写入路径正常 ⇒ 问题在"命令运行时 FIFO 的取数/水位"，回到 `IPTXWE`/`TXWMRK` 语义 |
// | `reclear ≠ 0` | 清 FIFO 没生效 ⇒ `IPTXFCR.CLRIPTXF` 的用法有问题 |
//
// `ATDFEN`/`ARDFEN` 是 `MCR0` 的 bit7/bit6（`PERI_FLEXSPI.h:189-203`），
