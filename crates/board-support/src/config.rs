//    在入口处拿整段长度去判会让任何跨页写直接被 `SpansPage` 拒掉
//    （真机：`bad=3`）。⇒ `store.rs` 的 `program` 改为按单页长度过闸门；
// 3. `Intr::note` 是诊断值的唯一正确通道（`decode` 只保留低 12 位，
//    塞进 `raw` 的高位会被当场清掉）。
//
// ## ✅ 2026-10-13 深夜：**已解决** —— 跨页/非对齐/RMW 全部通过
//
// ```text
// flash : 自证(跨页+非对齐) PASS 擦写三例=ok bad=0 擦回=ok sector=0x1fff000
// flash : reg 写路径自证 PASS detail=0 擦回=ok sector=0x1fff000
// MPU 已启用 · I-cache ON · D-cache ON · 8 个区域
// ```
//
// **两个独立根因，缺一不可：**
//
// ### 根因 A：`program_page` 只发了一个 burst（32 B）
//
// 介质层走 `flexspi_ip::program_page`，而它此前只调一次 `ip_write`、
// **把返回的游标（实际写出字节数）丢掉** —— 一个 IP 命令最多送出
// `ip_burst_bytes()`（半个 TX FIFO = 32 B），所以一页 256 B 只落了前 32 B。
// 页对齐自证之所以能过，是因为它走的是 `program_page_staged`（那条路分块是对的）。
// **修法：两条路径共用同一个函数**，顺手消灭"两份分块逻辑各自漂移"的可能 ——
// 本项目已有过一次教训：分叉的判据比没有判据更危险。
//
// ### 根因 B：寄存器写路径**没有内核 D-Cache 维护**（决定性对照）
//
// 把编程从 ROM 路径切到寄存器路径之后，**两条自证同时失效**。决定性对照：
// **把 `MPU_AND_CACHE_ENABLED` 置 false（D-Cache 关）后两条自证全部 PASS**
// ⇒ 写入路径本身完全正确，唯一障碍是缓存一致性。
//
// ⚠️ 关键认知：**ROM 的 `clear_cache` 不够**。SDK 里它是
// `flexspi_clear_cache` → `flexspi_swreset`，清的是**控制器侧** AHB RX 缓冲/预取
//（勘误 ERR011207 的那一半），**不是 Cortex-M7 的 L1 D-Cache**。
// 我在这一轮先试了"只在写路径调 ROM 的 clear_cache"，两条自证**仍然失败** ——
// 那次失败正是把它与"缺缓存维护"区分开的证据。
//
// 修法：新增 [`crate::cache`] 模块，用 ARMv7-M 架构寄存器 `SCB.DCIMVAC`
//（`0xE000_EF5C`）按地址范围**失效** D-Cache；`cortex-m 0.7.9` 与 `imxrt-hal 0.6`
// **都没有**这个 API（已在 registry 源码核实），因此这 1 处 unsafe 不可避免，
// 已按流程记入 `unsafe.budget`（现 53/54，**未超预算**）。
//
// ---
//
// ## 附带的性能结论：控制器复位**绝不能放在内层循环里**
//
// 修好缓存维护之后，我在**每个 32 字节块**之后都调了 `clear_flash_cache()`。
// 这是错的：ROM 的 `clear_cache` 是 **FlexSPI 软件复位**，会清掉控制器侧的
// **AHB 预取缓冲**，而那个缓冲对 XIP 读性能的影响量级是 **70 倍** ——
// 真机实测同一份基准（映射前 64 KiB 轮转读 16 遍）：
//
// ```text
// 预取缓冲预热：flash rd : 3401993 KiB/s（1024 KiB / 301 µs）
// 缓冲被清后  ：flash rd :   48473 KiB/s（1024 KiB / 21125 µs）
// ```
//
// 而 48 MB/s ≈ 100 MHz × 4 bit 的**物理上限** ⇒ **后者才是诚实的器件带宽**，
// 前者是缓冲命中的假象。一页 256 B 分 8 块 ⇒ 每页复位 8 次；
// 若代码在 XIP 里执行，每次复位都会让取指停顿。
//
// ⇒ 现行做法：内层循环**只做廉价的 D-Cache 失效**（`DCIMVAC`，每块一次），
// **控制器复位每次编程/擦除只做一次**（循环之后）。
//
// 这也解释了那个一度被记为"待查疑点"的 70 倍差异 —— 它不是回归，是**测量条件**。

