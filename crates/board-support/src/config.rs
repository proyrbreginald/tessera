//! 板级配置：**所有**与具体接线有关的取值都在这里，且每条都标注确认状态。
//!
//! # 为什么集中
//!
//! 把这些取值散在驱动代码里，会出现"改了引脚但忘了改注释"的漂移。
//! 集中之后有两个好处：
//!
//! 1. 审阅者只需看一个文件就能核对整块板的接线；
//! 2. `cargo xtask check-gaps` 只需扫一个文件就能列出**未确认项**，
//!    而这些未确认项就是当前交付的诚实边界。
//!
//! # 确认状态标记
//!
//! | 标记 | 含义 |
//! |------|------|
//! | ✅ | 有原理图/数据手册的直接依据（页码见 `docs/03-硬件/板级事实.md`） |
//! | 🟡 | 待确认：取值未知或存在矛盾来源，**不得**当作事实使用 |

/// 24 MHz 晶振（原理图 `Y1`，负载电容 11 pF）。✅
pub const XTAL_HZ: u32 = 24_000_000;

/// 调试控制台波特率：115200 8N1。✅（工程约定，非芯片/原理图规定）
pub const CONSOLE_BAUD: u32 = 115_200;

/// 控制台 UART 功能时钟：直接取 24 MHz 晶振。✅
///
/// 取晶振而不是 PLL3/6 的理由：**不依赖 PLL3 是否锁定**。时钟树配错时，
/// 控制台仍能出字 —— 这在 bring-up 阶段的诊断价值远大于 0.16% 的波特率误差。
pub const CONSOLE_CLOCK_HZ: u32 = XTAL_HZ;

/// 时基（PIT）计数频率。✅
///
/// PERCLK 取晶振、分频 1 → 24 MHz。PIT0/PIT1 链成 64 位自由计数器，
/// 因此 `now()` 的分辨率是 1/24 µs ≈ 41.7 ns。
pub const TIMEBASE_HZ: u32 = XTAL_HZ;

/// 1 ms 心跳的 PIT 装载值。
pub const TICK_TICKS: u32 = TIMEBASE_HZ / 1_000;

/// 每微秒的时基刻度数（24 MHz → 24）。
///
/// ⚠️ 曾经把"刻度 → 微秒"写成 `ticks / TIMEBASE_HZ`，那是把 1 秒算成 1 微秒
/// （24e6 刻度 = 1 秒，而不是 1 微秒），于是时间慢 100 万倍。
/// 正确换算是除以**每微秒的刻度数**。
pub const TICKS_PER_MICRO: u32 = TIMEBASE_HZ / 1_000_000;

/// 控制台 UART 实例：LPUART1。✅
pub const CONSOLE_UART_INSTANCE: u8 = 1;
/// 控制台 TX 焊盘。✅ `GPIO_AD_B0_06`（球 105，ALT2）→ `J7` pin11。
pub const CONSOLE_TX_PAD: &str = "GPIO_AD_B0_06";
/// 控制台 RX 焊盘。✅ `GPIO_AD_B0_07`（球 101，ALT2）→ `J7` pin12。
pub const CONSOLE_RX_PAD: &str = "GPIO_AD_B0_07";

