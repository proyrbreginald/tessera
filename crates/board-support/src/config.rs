// ---------------------------------------------------------------- 外部 SDRAM

/// SDRAM 基址。SEMC 的 SDRAM 分区固定在 `0x8000_0000` 起。
///
/// 与 Flash（`0x6000_0000`）不同，这里**不在启动链路上**：SDRAM 由固件自己初始化，
/// 初始化失败只影响用到它的功能，不会导致无法启动。这一点决定了错误处置策略：
/// 初始化失败应当**报告并降级**，而不是让设备变砖。
pub const SDRAM_BASE: u32 = 0x8000_0000;

/// 允许的 SEMC 最高时钟。
///
/// 取 70 MHz 的理由：既有 C 固件在这块板上按 62.5 MHz 验证过 SDRAM，
/// 而 SEMC 的时钟只能由 `PLL2_PFD2` 分频得到（不能改 PLL，见 `sdram` 模块文档），
/// 因此取一个略高于已验证值、但仍远低于器件 166 MHz 上限的目标，
/// 让分频后的实际值尽量贴近已验证工况。
pub const SEMC_CLOCK_MAX_HZ: u32 = 70_000_000;

/// SEMC 时钟的合理下限。低于它说明 PLL/PFD 没按预期工作（而不是"分频取大了"）。
pub const SEMC_CLOCK_MIN_HZ: u32 = 20_000_000;

/// SEMC 总线超时周期（SDK 默认 0x1F）。
pub const SEMC_BUS_TIMEOUT_CYCLES: u32 = 0x1F;
/// SEMC 命令超时周期（SDK 默认 0xFF）。
pub const SEMC_CMD_TIMEOUT_CYCLES: u32 = 0xFF;

/// 是否在上电时对 SDRAM 做完整自检（POST）。
///
/// 默认**打开**：bring-up 阶段"每次上电都证明内存可用"比省下 2 秒重要得多。
/// 量产固件应当关掉它（或改成由命令触发），因为 SDRAM 不在启动链路上，
/// 它的故障不需要在上电时就阻断启动。这个开关存在的意义就是把该决定显式化。
pub const SDRAM_POST_AT_BOOT: bool = true;

/// 启动时是否执行 **Flash 擦写自证**。
///
/// 打开时：在 `idle` 的循环之前对**文件系统最后一个扇区**做
/// `擦除 → 编程一页地址派生图案 → 回读比对 → 擦回空白`，并把结果打成一行。
///
/// 为什么默认关闭：它**每次启动都写一次器件**（一次擦 + 一次页编程）。一次性验证合适；
/// 长期打开只是给 Flash 增加无谓磨损。目标、图案与判据见 `nor_flash::selftest`。
///
/// # 当前结论速览（想读细节再看下面的**过程日志**）
///
/// **已解决**：寄存器级页编程 + ROM 擦除在真机上全部通过
/// （`自证(跨页+非对齐) PASS 擦写三例=ok bad=0`；`reg 写路径自证 PASS detail=0`）。
/// 两个独立根因：①介质层把分块游标丢掉，一页只发了一个 32 B 突发；②寄存器写路径
/// 缺 **D-Cache 维护**（XIP 可缓存 ⇒ 写后回读命中旧行）。
///
/// 下面保留的是 2026-10-12/13 的**排查过程**（几条被排除的假设、真机实测数字与
/// 踩过的坑）。阅读时请把它当历史记录，而不是当前状态。
///
/// 2026-10-12 真机实测（打开一次）：`自证 PASS sector=0x1fff000 detail=0 擦回=ok` ——
/// ROM 驱动的擦除/页编程/回读在真实器件上全部成立，且目标扇区擦回空白后
/// 文件系统挂载看不到任何痕迹（446 块 × 64 KiB，0 个文件）。
///
/// 随后改成**经存储介质层**再验一次（`自证(经介质) PASS`），证明的是接线后的完整路径：
/// 闸门判据 → 逐扇区擦除 → 读-改-写整页编程 → ROM 驱动。
///
/// # ⚠️ 扩展成四用例后**报 FAIL**（2026-10-12；已于 10-13 深夜定位并修复）
///
/// ```
/// flash : 自证4用例 FAIL erase4k=35009us erase64k=557679us prog3=255us
///         rw=FAIL cross=FAIL page=FAIL untouched=ok bad=140 擦回=ok
/// ```
///
/// **实测数字（这三个此前一直是空的，现在有了）**：擦 4 KiB 扇区 ≈ **35 ms**、
/// 擦 64 KiB 块 ≈ **557 ms**、编程一页 ≈ **85 µs**。它们直接印证了"擦写绝不能进关中断"
/// 这条设计决定（`with_fs` 的文档里写的正是这件事）。
///
/// **`bad=140` 的含义**：`bad = 位置 + 100` ⇒ **写入范围内的第一个字节**就不符。
/// 已经排除的两个原因（都是这轮真修掉的）：
/// 1. 图案**不是绝对地址的纯函数**（混进了切片内下标，写入与核验算出不同期望值）；
/// 2. **缓存一致性**：XIP 可缓存 ⇒ 编程后回读可能命中旧行，而介质层的读-改-写更危险
///    （把陈旧内容整页写回）。已改为擦除/编程后调用 ROM 的 `clear_cache`。
///
/// **诊断结论（2026-10-12，一次运行就定性）**：
/// ```
/// bad=140 want=ad got=ff  head_got=ffffffff
/// ```
/// `head_got` 全是 `0xFF` = **擦除态** ⇒ **编程一个字节都没写进去**（不是"内容不对"），
/// 而 `program` 却返回了成功。
///
/// # ⚠️ 一处自我修正（避免下一轮沿着错假设走）
///
/// 我先前写"`erase4k≈35 ms` 说明擦除确实在做事"—— **这个推论不成立** ✗。
/// 自证的目标扇区**每次结束都会擦回空白**，所以它**本来就是擦除态**：
/// 耗时 35 ms 只说明"ROM 调用花了 35 ms"，**不能证明内容被改变了**。
/// ⇒ **"擦除有效"这件事从未被证明过**。
///
/// 于是更简约的假设是：**擦除与编程都静默无效，根因都在配置**。
///
/// # 下一步（两条，先做便宜的）
///
/// 1. **先证明擦除到底有没有用**（一页足矣）：在扇区里写入图案 → 读回确认"非擦除态"
///    → 擦除 → 读回应为全 `0xFF`。若第二步读到旧图案 ⇒ **擦除也无效** ⇒ 直接指向配置；
/// 2. **照 `FLEXSPI_NorFlash_GetConfig()` 在 RAM 里逐字段构造配置**
///    （`winshare/.../nor/flexspi_romapi.c`：tag/version/readSampleClkSrc/serialClkFreq/
///    sflashA1Size/csHoldTime/csSetupTime/deviceType/…/lookupTable 与
///    pageSize/sectorSize/blockSize/ipcmdSerialClkFreq），按字节偏移写并**配偏移断言**。
///    注意它用的是 **133 MHz**，而本板 FlexSPI 跑 **100 MHz**（dummy 0x06 只对该频率正确）
///    —— 这一处差异必须核对清楚，不能照抄。
///
/// # 已用真机二分排除的两条（2026-10-12 晚）
///
/// | 假设 | 结果 |
/// |---|---|
/// | 没调 `init(instance, config)` | ✗ **不是**根因（补上 `init` 后症状完全不变，且 `init` 返回成功） |
/// | ROM 要 **XIP 绝对地址**（`0x6000_0000+偏移`） | ✗ **不是** —— 传绝对地址时 ROM **瞬间返回错误**（`erase4k=33µs`、`擦回=FAIL`）⇒ **它要的是 Flash 内偏移** |
///
/// ⇒ 嫌疑**收敛到配置内容**：FCB 并不是 ROM 认的 `flexspi_nor_config_t`。
/// 偏移表（取自 SDK 头注释）已存进记忆库 `3e133f29`；下一步按它在 RAM 里逐字段构造。
/// 在那之前**不要**打开这个开关去猜。
///
/// # 第六条也排除了：把 LUT **装进控制器**之后，写使能仍然失败（2026-10-12 夜）
///
/// 我按官方 `FLEXSPI_UpdateLUT` 的流程（等空闲 → `LUTKEY=0x5AF0_5AF0` → `LUTCR=0x02` 解锁 →
/// 写 `LUT[index+i]` → `LUTCR=0x01` 上锁）把 5 条序列**直接装进控制器**，真机输出：
///
/// ```text
/// flexspi  : install LUT ok
/// flexspi  : reg rd status=0x00 intr=ok            ← 读仍然通（说明 LUT 装载生效）
/// flash    : reg 写路径自证 FAIL detail=1 擦回=FAIL ← 写使能仍失败
/// ```
///
/// ⇒ **"控制器里缺 LUT"这条假设排除了**：LUT 是我们装的、读通、而写使能依旧失败。
///
/// # 下一步（一次运行就能定位）
///
/// 把**触发写使能之后立刻读到的原始 `INTR`**、以及 `IPCR1`/`IPCMD`/`LUT[12..16]` 的**回读值**
/// 一起打出来：
/// - `LUT[12..16]` 回读 ⇒ 证明装载真的落在索引 3（而不是被谁覆盖/越界）；
/// - 原始 `INTR` ⇒ 是**授予错误**还是**命令错误**还是**根本没置 done**；
/// - `IPCR1` 回读 ⇒ 证明打包值真的写进去了。
///
/// 三者一起看基本不可能再有歧义；在那之前不要再改序列。
///
/// # 第六步：分段诊断把范围压到**写使能**，随后发现一条自相矛盾的硬事实（2026-10-12 深夜）
///
/// 分段诊断输出 `detail=1` ⇒ **写使能失败**（读状态走同一套机制却是通的）。
/// 于是离线看产物里的 LUT（`firmware.bin` 偏移 0x200 起、每序列 4 字）：
///
/// ```text
/// 索引 1（读状态，实际能用）: 0xd4d4d4d4 ×4   ← 解码是非法操作码 53，**不是 LUT**
/// 索引 3（写使能，失败）    : 0xd4d4d4d4 ×4
/// 索引 5（擦除）/ 9（页编程）: 0xd4d4d4d4 ×4
/// ```
/// 进一步全文件搜索 `READ_STATUS`（`0x25010505`）与 `WRITE_ENABLE`（`0x00000506`）的编码：
/// **一处都没有**。
///
/// 而 `cargo xtask check-image` **声称从链接产物断言过 LUT 三个序列的 4 字节地址相位**。
/// ⇒ **两者必有一处假设是错的**：要么产物里真的没有 LUT（运行时 LUT 来自别处），
/// 要么"`.bin` 字节偏移 == Flash 偏移"这个假设不成立。
/// **在裁定之前不要再猜写使能的序列** —— 先按 `check-image` 的定位方式
/// （ELF 段/符号）确认 LUT 到底在哪，以及运行时控制器里的 LUT 是从哪儿来的。
/// 这条很可能是整条 ROM 路径"静默无效"的真正根源。
/// ⚠️ 注意：单页那次 `PASS` 是**弱证据**（那条页写入前从没被读过 ⇒ 没覆盖读-改-写与缓存路径），
/// 而"配置不对"这件事**只有多用例自证才会暴露** —— 这正是扩展测试的价值。
/// ⚠️ 注意：单页那次 `PASS` 是**弱证据** —— 那条页在写入前从没被读过（缓存里没有旧行），
/// 所以它没有覆盖读-改-写与缓存这两条路径。
pub const FLASH_SELFTEST_AT_BOOT: bool = false;
/// **FlexCAN2 loopback 自证**（写序列 + 勘误 ERR005829 规避 + 邮箱数据通路）。
///
/// # 它验证什么
///
/// 内部回环（`CTRL1[LPB]`）自收自发：不需要总线对端、不需要位时序对齐，
/// 但覆盖"时钟门控 → 复位 → 位时序 → 邮箱武装 → 发送 → 接收"整条数据通路。
/// 只读探针（`flexcan::probe`）**常开**；本开关控制的是这条**写**路径，
/// 所以默认只在 bring-up 阶段打开。
///
/// # 当前真机状态（2026-10-13 最新一次抓包）
///
/// ```text
/// can : mcr=0x5980000f frz_ack=true 邮箱=64 PE 时钟=12000000 Hz 波特率=1000000 bps
/// can : loopback 自证 FAIL stage=7 诊断值=0x40000084
/// ```
///
/// 解码：TX 邮箱已回到 INACTIVE（帧发出、无错误计数），但 RX 邮箱始终 EMPTY
/// ⇒ **发送侧完成，接收路径未通**。已用真机逐步排除：
/// ① 时钟门控（`CCGR0[CG9]` + `CG10`，写完读回）；② 时钟源（`CSCMR2[CAN_CLK_SEL]=1`
/// 选 24 MHz 晶振，PE 实测 12 MHz）；③ `MCR` 位号；④ `RXIMR` 写时机
/// （必须在 Freeze 模式里写）。下一步应借助第二块板/示波器确认总线电气，
/// 而不是继续改序列（**猜**是被禁止的）。
///
/// ⚠️ 勘误 `ERR005829`（MB0 必须保留为 INACTIVE）**不能**因为"别人的代码里没有"
/// 就删掉 —— 真机上删掉它会直接卡死（见 `flexcan::reserve_mb0` 的注释）。
pub const CAN_LOOPBACK_SELFTEST: bool = true;

